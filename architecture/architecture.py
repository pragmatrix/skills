def parent_of(module):
    return module.rsplit("::", 1)[0] if "::" in module else ""


def relative(path, parent):
    if parent and path == parent:
        return "self"
    return path[len(parent) + 2:] if parent and path.startswith(parent + "::") else path


def project(source, target):
    """The sibling edge a module dependency becomes: under the modules' common
    parent, between the two children they lie in. A module's own items are the
    child `<module>::self`."""
    s, t = source.split("::"), target.split("::")
    common = 0
    while common < min(len(s), len(t)) and s[common] == t[common]:
        common += 1
    parent = "::".join(s[:common])
    a = parent + "::self" if len(s) == common else "::".join(s[:common + 1])
    b = parent + "::self" if len(t) == common else "::".join(t[:common + 1])
    return parent, a, b


def shown(endpoint):
    return endpoint[:-6] + " (self)" if endpoint.endswith("::self") else endpoint


def strongly_connected(graph):
    """Tarjan's components of a {node: set(successors)} graph, each sorted."""
    index, low, stack, on_stack, result = {}, {}, [], set(), []

    def visit(node):
        index[node] = low[node] = len(index)
        stack.append(node)
        on_stack.add(node)
        for succ in sorted(graph[node]):
            if succ not in index:
                visit(succ)
                low[node] = min(low[node], low[succ])
            elif succ in on_stack:
                low[node] = min(low[node], index[succ])
        if low[node] == index[node]:
            members = []
            while True:
                member = stack.pop()
                on_stack.discard(member)
                members.append(member)
                if member == node:
                    break
            result.append(sorted(members))

    for node in sorted(graph):
        if node not in index:
            visit(node)
    return result


def shortest_path(graph, start, goal):
    previous, queue = {start: None}, [start]
    while queue:
        node = queue.pop(0)
        for succ in sorted(graph[node]):
            if succ not in previous:
                previous[succ] = node
                if succ == goal:
                    path = [goal]
                    while previous[path[-1]] is not None:
                        path.append(previous[path[-1]])
                    return path[::-1]
                queue.append(succ)
    return None


def analyze(snap):
    modules = set(snap["modules"])
    components = {c["name"]: c for c in snap["components"]}
    listed = defaultdict(list)
    for c in snap["components"]:
        for path in c["realized_by"]:
            listed[path].append(c["name"])

    def components_of(module):
        segments = module.split("::")
        for end in range(len(segments), 0, -1):
            path = "::".join(segments[:end])
            if path in listed:
                return tuple(sorted(listed[path]))
        return ()

    mapping = {m: components_of(m) for m in modules}

    edges = defaultdict(set)
    pairs = defaultdict(set)
    for source, target, source_item, target_item in snap["uses"]:
        parent, a, b = project(source, target)
        edges[(parent, a, b)].add(f"{relative(source_item, parent)} -> {relative(target_item, parent)}")
        pairs[(source, target)].add(f"{relative(source_item, parent)} → {relative(target_item, parent)}")

    crate_of = lambda module: module.split("::", 1)[0]
    used_crates = {(crate_of(s), crate_of(t)) for s, t, _, _ in snap["uses"]}
    used_externals = {(crate_of(m), e) for m, e in snap["external_uses"]}
    unused_crates = sorted((c, d) for c, info in snap["crates"].items()
                           for d in info["deps"] if (c, d) not in used_crates)
    unused_externals = sorted((c, e) for c, info in snap["crates"].items()
                              for e in info["externals"] if (c, e) not in used_externals)

    found = check(modules, components, listed, mapping, pairs)
    found["findings"] += [f"Unused crate dependency: `{c} → {d}`. No module-level `use` or signature reaches it."
                          for c, d in unused_crates + unused_externals]
    return {
        "modules": modules,
        "components": components,
        "listed": listed,
        "mapping": mapping,
        "edges": edges,
        "unused_crates": unused_crates,
        "unused_externals": unused_externals,
        **found,
    }


def check(modules, components, listed, mapping, pairs):
    """Findings in a fixed category order, and the component edges they draw."""
    none = {"findings": [], "unexplained": set(), "transitive": set(), "stale": set()}
    if not components:
        none["findings"].append("No components are declared in `architecture.toml` yet.")
        return none
    unknown = [f"Unknown component: {n} depends on {d}, which is not declared."
               for n in sorted(components) for d in components[n]["depends_on"] if d not in components]
    unknown += [f"Unknown path: `{p}`, listed by {', '.join(sorted(listed[p]))}, is no crate or module."
                for p in sorted(listed) if p not in modules]
    deps = {n: {d for d in c["depends_on"] if d in components} for n, c in components.items()}
    reach = {n: set() for n in deps}
    for n in deps:
        stack = list(deps[n])
        while stack:
            d = stack.pop()
            if d not in reach[n]:
                reach[n].add(d)
                stack.extend(deps[d])

    evidence, unexplained, transitive = set(), set(), set()
    unexplained_findings, transitive_findings = [], []
    for (source, target), reaches in sorted(pairs.items()):
        cf, ct = mapping.get(source, ()), mapping.get(target, ())
        if not cf or not ct:
            continue
        direct = {(a, b) for a in cf for b in ct if b in deps[a]}
        evidence |= direct
        if direct or set(cf) & set(ct):
            continue
        uses = ", ".join(f"`{r}`" for r in sorted(reaches))
        longer = sorted((a, b) for a in cf for b in ct if b in reach[a])
        if longer:
            transitive.update(longer)
            via = "; ".join(f"{a} reaches {b} only through {' → '.join(shortest_path(deps, a, b)[1:-1])}"
                            for a, b in longer)
            transitive_findings.append(f"Transitive: `{source} → {target}` ({uses}). {via}.")
        else:
            missing = sorted((a, b) for a in cf for b in ct)
            unexplained.update(missing)
            why = "; ".join(f"{a} has no path to {b}" for a, b in missing)
            unexplained_findings.append(f"Unexplained: `{source} → {target}` ({uses}). {why}.")

    unmapped = [f"Unmapped: `{m}` belongs to no component." for m in sorted(modules) if not mapping[m]]
    stale = {(a, b) for a in deps for b in deps[a] if (a, b) not in evidence}
    stale_findings = [f"Stale: {a} → {b} has no code dependency behind it." for a, b in sorted(stale)]
    cycles = [f"Cycle: {', '.join(scc)} depend on each other." for scc in strongly_connected(deps)
              if len(scc) > 1 or scc[0] in deps[scc[0]]]
    return {
        "findings": unknown + unexplained_findings + transitive_findings + unmapped + stale_findings + cycles,
        "unexplained": unexplained,
        "transitive": transitive,
        "stale": stale,
    }


