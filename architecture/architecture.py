# Mermaid rendering, shared by ARCHITECTURE.md and the diff view.


def quote(text):
    return text.replace('"', "#quot;")


def unique_ids(names, make):
    ids, used = {}, set()
    for name in sorted(names):
        base = make(name)
        if base in MERMAID_KEYWORDS:
            base = "m_" + base
        candidate, n = base, 2
        while candidate in used:
            candidate, n = f"{base}_{n}", n + 1
        used.add(candidate)
        ids[name] = candidate
    return ids


def edge_line(ids, edge):
    """One edge as Mermaid. An edge is a dict with a, b, and optional label,
    dotted, comments, and style."""
    arrow = "-.->" if edge.get("dotted") else "-->"
    label = f'|"{quote(edge["label"])}"|' if edge.get("label") else ""
    lines = [f"    {ids[edge['a']]} {arrow}{label} {ids[edge['b']]}"]
    lines += [f"    %% {c}" for c in edge.get("comments", [])]
    return lines


def link_styles(edges):
    return [f"    linkStyle {i} {e['style']}" for i, e in enumerate(edges) if e.get("style")]


def code_graph(modules, edges, node_styles):
    """The nested code graph: crates and modules with submodules are boxes, and
    the box's own items are its `self` node."""
    children = defaultdict(list)
    for m in modules:
        children[parent_of(m)].append(m)
    selves = {e[k] for e in edges for k in ("a", "b") if e[k].endswith("::self")}
    ids = unique_ids(modules | selves, lambda p: p.replace("::", "__"))
    lines = ["```mermaid", "flowchart TD"]

    def emit(parent, depth):
        indent = "    " * depth
        for m in sorted(children[parent]):
            name = quote(m.rsplit("::", 1)[-1])
            if children[m]:
                lines.append(f'{indent}subgraph {ids[m]}["{name}"]')
                if m + "::self" in selves:
                    lines.append(f'{indent}    {ids[m + "::self"]}[["self"]]')
                emit(m, depth + 1)
                lines.append(f"{indent}end")
            else:
                lines.append(f'{indent}{ids[m]}["{name}"]')

    emit("", 1)
    for e in edges:
        lines += edge_line(ids, e)
    lines += link_styles(edges)
    lines += [f"    style {ids[m]} {s}" for m, s in sorted(node_styles.items())]
    lines.append("```")
    return lines


def component_graph(names, edges):
    ids = unique_ids(names, lambda n: "c_" + (re.sub(r"\W+", "_", n.lower()).strip("_") or "x"))
    lines = ["```mermaid", "flowchart TD"]
    lines += [f'    {ids[n]}["{quote(n)}"]' for n in sorted(names)]
    for e in edges:
        lines += edge_line(ids, e)
    lines += link_styles(edges)
    lines.append("```")
    return lines


def external_graph(edges, node_styles=None):
    """Modules and crates on the left, external packages on the right."""
    sources = {e["a"] for e in edges}
    targets = {e["b"] for e in edges}
    ids = {**unique_ids(sources, lambda p: "m_" + p.replace("::", "__")),
           **unique_ids(targets, lambda p: "x_" + re.sub(r"\W", "_", p))}
    lines = ["```mermaid", "flowchart LR"]
    lines += [f'    {ids[t]}(["{quote(t)}"])' for t in sorted(targets)]
    lines += [f'    {ids[s]}["{quote(s)}"]' for s in sorted(sources)]
    for e in edges:
        lines += edge_line(ids, e)
    lines += link_styles(edges)
    lines += [f"    style {ids[n]} {s}" for n, s in sorted((node_styles or {}).items())]
    lines.append("```")
    return lines


