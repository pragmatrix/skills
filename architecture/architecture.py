def load_components(root):
    """The canonical components and the file's header comment, or none."""
    path = os.path.join(root, TOML)
    if not os.path.exists(path):
        return [], None
    with open(path, encoding="utf-8") as f:
        text = f.read()
    try:
        data = tomllib.loads(text)
    except tomllib.TOMLDecodeError as error:
        die(f"{path}: {error}")
    unknown = set(data) - {"component"}
    if unknown:
        die(f"{path}: unknown top-level keys {sorted(unknown)}")
    components, names = [], set()
    for raw in data.get("component", []):
        extra = set(raw) - {"name", "responsibility", "realized_by", "depends_on"}
        if extra:
            die(f"{path}: unknown keys {sorted(extra)} in component {raw.get('name')!r}")
        name = raw.get("name")
        if not isinstance(name, str) or not name.strip():
            die(f"{path}: a component has no name")
        if name in names:
            die(f"{path}: component {name!r} is declared twice")
        names.add(name)
        for key in ("realized_by", "depends_on"):
            value = raw.get(key, [])
            if not isinstance(value, list) or not all(isinstance(v, str) for v in value):
                die(f"{path}: {key} of {name!r} is no list of strings")
        components.append({
            "name": name,
            "responsibility": str(raw.get("responsibility", "")),
            "realized_by": sorted(set(raw.get("realized_by", []))),
            "depends_on": sorted(set(raw.get("depends_on", []))),
        })
    header = []
    for line in text.splitlines():
        if not line.startswith("#"):
            break
        header.append(line)
    return sorted(components, key=lambda c: c["name"]), "\n".join(header) or None


def canonical_toml(header, components):
    def string(s):
        return json.dumps(s, ensure_ascii=False)

    def strings(values):
        return "[" + ", ".join(string(v) for v in values) + "]"

    parts = [header or DEFAULT_HEADER, ""]
    for c in components:
        parts += ["[[component]]",
                  f"name = {string(c['name'])}",
                  f"responsibility = {string(c['responsibility'])}",
                  f"realized_by = {strings(c['realized_by'])}",
                  f"depends_on = {strings(c['depends_on'])}",
                  ""]
    return "\n".join(parts)


