# Diff of two snapshots.


def diff(base, head, base_label, head_label):
    """The change summary as text sections, and the diff view as Markdown."""
    b, h = analyze(base), analyze(head)
    sections = []

    def section(title, lines):
        if lines:
            sections.append((title, lines))

    section("Modules", [f"+ `{m}`" for m in sorted(h["modules"] - b["modules"])] +
            [f"− `{m}`" for m in sorted(b["modules"] - h["modules"])])

    code = []
    for key in sorted(set(b["edges"]) | set(h["edges"])):
        _, a, z = key
        before, after = b["edges"].get(key), h["edges"].get(key)
        arrow = f"`{shown(a)} → {shown(z)}`"
        if before is None:
            code.append(f"+ {arrow}: " + ", ".join(f"`{r}`" for r in sorted(after)))
        elif after is None:
            code.append(f"− {arrow}: " + ", ".join(f"`{r}`" for r in sorted(before)))
        elif before != after:
            code.append(f"~ {arrow}: " + ", ".join([f"+ `{r}`" for r in sorted(after - before)] +
                                                    [f"− `{r}`" for r in sorted(before - after)]))
    section("Code edges", code)

    b_ext, h_ext = {tuple(u) for u in base["external_uses"]}, {tuple(u) for u in head["external_uses"]}
    section("External crate uses", [f"+ `{m} → {e}`" for m, e in sorted(h_ext - b_ext)] +
            [f"− `{m} → {e}`" for m, e in sorted(b_ext - h_ext)])

    def declared(snap):
        return {(c, d) for c, info in snap["crates"].items() for d in info["deps"] + info["externals"]}

    section("Crate dependencies (Cargo.toml)",
            [f"+ `{c} → {d}`" for c, d in sorted(declared(head) - declared(base))] +
            [f"− `{c} → {d}`" for c, d in sorted(declared(base) - declared(head))])

    comps = []
    for name in sorted(set(b["components"]) | set(h["components"])):
        before, after = b["components"].get(name), h["components"].get(name)
        if before is None:
            comps.append(f"+ {name}: depends on {', '.join(after['depends_on']) or 'nothing'}, "
                         f"realized by {', '.join(f'`{p}`' for p in after['realized_by']) or 'nothing'}")
        elif after is None:
            comps.append(f"− {name}")
        else:
            changes = []
            for key, what in (("depends_on", "depends on"), ("realized_by", "realized by")):
                added = sorted(set(after[key]) - set(before[key]))
                removed = sorted(set(before[key]) - set(after[key]))
                if added or removed:
                    changes.append(f"{what} " + ", ".join([f"+ {v}" for v in added] + [f"− {v}" for v in removed]))
            if before["responsibility"] != after["responsibility"]:
                changes.append(f"responsibility now: {after['responsibility']}")
            if changes:
                comps.append(f"~ {name}: " + "; ".join(changes))
    section("Components", comps)

    b_find, h_find = set(b["findings"]), set(h["findings"])
    section("Check", [f"new: {f}" for f in h["findings"] if f not in b_find] +
            [f"resolved: {f}" for f in b["findings"] if f not in h_find])

    view = [f"# Architecture changes: {base_label} → {head_label}", "",
            "Generated by `architecture.py`. Green is added, red is removed, and blue is a code edge "
            "whose reaches changed. Only changed code edges carry labels: their changed reaches, "
            "marked `+` or `−`.", "", "## Summary", ""]
    if not sections:
        view.append("No architecture changes.")
    for title, lines in sections:
        view += [f"### {title}", ""] + [f"- {line}" for line in lines] + [""]

    names = set(b["components"]) | set(h["components"])
    if names:
        def declared_edges(an):
            return {(a, d) for a, c in an["components"].items() for d in c["depends_on"]
                    if d in an["components"]}
        before, after = declared_edges(b), declared_edges(h)
        edges = []
        for a, z in sorted(before | after):
            style = GREEN if (a, z) not in before else RED if (a, z) not in after else None
            edges.append({"a": a, "b": z, "dotted": (a, z) not in after, "style": style})
        edges += [{"a": a, "b": z, "dotted": True, "label": "unexplained", "style": UNEXPLAINED}
                  for a, z in sorted(h["unexplained"]) if a in names and z in names]
        edges += [{"a": a, "b": z, "dotted": True, "label": "transitive", "style": TRANSITIVE}
                  for a, z in sorted(h["transitive"]) if a in names and z in names]
        view += ["## Components", ""] + component_graph(names, edges) + [""]

    modules = b["modules"] | h["modules"]
    edges = []
    for key in sorted(set(b["edges"]) | set(h["edges"])):
        _, a, z = key
        before, after = b["edges"].get(key, set()), h["edges"].get(key, set())
        if not before:
            label, style = "<br/>".join(f"+ {r}" for r in sorted(after)), GREEN
        elif not after:
            label, style = "<br/>".join(f"− {r}" for r in sorted(before)), RED
        elif before != after:
            label = "<br/>".join([f"+ {r}" for r in sorted(after - before)] +
                                 [f"− {r}" for r in sorted(before - after)])
            style = BLUE
        else:
            label, style = None, None
        edges.append({"a": a, "b": z, "label": label, "style": style})
    styles = {m: ADDED_NODE for m in h["modules"] - b["modules"]}
    styles |= {m: REMOVED_NODE for m in b["modules"] - h["modules"]}
    if modules:
        view += ["## Code graph", ""] + code_graph(modules, edges, styles) + [""]

    changed = [{"a": m, "b": e, "style": GREEN} for m, e in sorted(h_ext - b_ext)]
    changed += [{"a": m, "b": e, "style": RED, "dotted": True} for m, e in sorted(b_ext - h_ext)]
    if changed:
        view += ["## External crates", ""] + external_graph(sorted(changed, key=lambda e: (e["a"], e["b"]))) + [""]

    summary = "\n\n".join(f"{title}:\n" + "\n".join(lines) for title, lines in sections)
    return summary or "No architecture changes.", "\n".join(view).rstrip("\n") + "\n"


