def cell(text):
    return text.replace("|", "\\|").replace("\n", " ")


def numbered(items):
    return [f"{i}. {item}" for i, item in enumerate(items, 1)]


def render_block(snap, an):
    out = [BEGIN, "", "## Components", ""]
    components = an["components"]
    if components:
        out += ["Arrows point from a component to the components it depends on, as declared in "
                "`architecture.toml`. Code dependencies that the declarations do not explain are "
                "drawn dashed, see the legend.", ""]
        edges = [{"a": a, "b": b, "dotted": (a, b) in an["stale"],
                  "style": STALE if (a, b) in an["stale"] else None}
                 for a in sorted(components) for b in components[a]["depends_on"] if b in components]
        edges += [{"a": a, "b": b, "dotted": True, "label": "unexplained", "style": UNEXPLAINED}
                  for a, b in sorted(an["unexplained"])]
        edges += [{"a": a, "b": b, "dotted": True, "label": "transitive", "style": TRANSITIVE}
                  for a, b in sorted(an["transitive"])]
        out += component_graph(set(components), edges)
        out += ["", "| Component | Responsibility | Realized by | Depends on |", "|---|---|---|---|"]
        for name in sorted(components):
            c = components[name]
            out.append(f"| {cell(name)} | {cell(c['responsibility'])} | "
                       f"{', '.join(f'`{p}`' for p in c['realized_by'])} | {cell(', '.join(c['depends_on']))} |")
        shared = sorted(p for p, names in an["listed"].items() if len(names) > 1)
        if shared:
            out += ["", "Paths listed under several components:", ""]
            out += [f"- `{p}`: {', '.join(sorted(an['listed'][p]))}" for p in shared]
    else:
        out.append("No components are declared yet. The architecture skill proposes them from the code graph.")

    out += ["", "## Check", ""]
    out += numbered(an["findings"]) if an["findings"] else ["No findings."]

    out += ["", "## Code graph", "",
            "One diagram holds every crate and module of the workspace. A `use` or a signature in a "
            "descendant becomes one edge between the two siblings it lies in, so an arrow may start "
            "or end at a box. The `%%` lines under an edge are its reaches: the used items behind it, "
            "with paths relative to the common parent and each item at the path where it is defined.", ""]
    edges = [{"a": a, "b": b, "comments": sorted(r)} for (_, a, b), r in sorted(an["edges"].items())]
    edges += [{"a": c, "b": d, "dotted": True, "label": "unused"} for c, d in an["unused_crates"]]
    grey = {m: GREY_NODE for m in an["modules"] if components and not an["mapping"][m]}
    out += code_graph(an["modules"], edges, grey)

    out += ["", "## External crates", ""]
    externals = [{"a": m, "b": e} for m, e in snap["external_uses"]]
    externals += [{"a": c, "b": e, "dotted": True, "label": "unused"} for c, e in an["unused_externals"]]
    if externals:
        out += ["Each arrow points from the deepest module that uses an external crate to that crate.", ""]
        out += external_graph(sorted(externals, key=lambda e: (e["a"], e["b"])))
    else:
        out.append("No external crates.")
    for kind, title in (("dev", "Dev-dependencies"), ("build", "Build dependencies")):
        listed = [f"`{c}`: {', '.join(info[kind])}" for c, info in sorted(snap["crates"].items()) if info[kind]]
        if listed:
            out += ["", f"{title}, not checked: " + "; ".join(listed) + "."]

    out += ["", "## Legend", "",
            "| Mark | Meaning |",
            "|---|---|",
            "| Solid arrow | A dependency. In the code graph the source uses the target, and among components it is declared. |",
            "| Dashed red arrow, *unexplained* | A code dependency that no declared component path explains. |",
            "| Dashed orange arrow, *transitive* | A code dependency that only a longer component path explains. |",
            "| Dotted grey arrow | A declared component dependency with no code behind it. |",
            "| Dotted arrow, *unused* | A `Cargo.toml` dependency that no `use` or signature reaches. |",
            "| Box | A crate, or a module with submodules. |",
            "| Double-bordered node, `self` | The items of a box's own file, as opposed to its submodules. |",
            "| Grey node or box | A module in no component. |",
            "| Rounded node | An external crate. |",
            "| `%%` line (source only) | A reach: a used item behind the edge above it. |",
            "", END]
    return "\n".join(out)


def write_doc(root, block):
    path = os.path.join(root, DOC)
    if os.path.exists(path):
        with open(path, encoding="utf-8") as f:
            text = f.read()
        start, end = text.find(BEGIN), text.find(END)
        if start != -1 and end != -1:
            text = text[:start] + block + text[end + len(END):]
        else:
            text = text.rstrip("\n") + "\n\n" + block + "\n"
    else:
        text = "# Architecture\n\n" + block + "\n"
    with open(path, "w", encoding="utf-8") as f:
        f.write(text)


