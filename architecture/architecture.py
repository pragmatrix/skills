def cmd_update(args):
    root = args.root
    components, header = load_components(root)
    if header is not None or components:
        text = canonical_toml(header, components)
        path = os.path.join(root, TOML)
        with open(path, encoding="utf-8") as f:
            if f.read() != text:
                with open(path, "w", encoding="utf-8") as w:
                    w.write(text)
    snap = extract(root)
    an = analyze(snap)
    write_doc(root, render_block(snap, an))
    print(f"Updated {os.path.join(root, DOC)}.")
    print("\n".join(numbered(an["findings"])) if an["findings"] else "No findings.")


def write_json(path, data):
    with open(path, "w", encoding="utf-8") as f:
        json.dump(data, f, indent=1, sort_keys=True, ensure_ascii=False)
        f.write("\n")


def read_snapshot(path):
    if path == "-":
        return empty_snapshot()
    with open(path, encoding="utf-8") as f:
        return json.load(f)


def cmd_snapshot(args):
    snap = snapshot_rev(args.rev, args.root) if args.rev else extract(args.root)
    write_json(args.output, snap)


def cmd_diff(args):
    summary, view = diff(read_snapshot(args.base), read_snapshot(args.head),
                         args.base_label or args.base, args.head_label or args.head)
    print(summary)
    if args.view:
        with open(args.view, "w", encoding="utf-8") as f:
            f.write(view)
        print(f"\nDiff view: {args.view}")


def cmd_view(args):
    base = snapshot_rev(args.base, args.root)
    head = extract(args.root)
    summary, view = diff(base, head, args.base, "working tree")
    fd, path = tempfile.mkstemp(prefix="architecture-view-", suffix=".md")
    with os.fdopen(fd, "w", encoding="utf-8") as f:
        f.write(view)
    print(summary)
    print(f"\nDiff view: {path}")


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    commands = parser.add_subparsers(dest="command", required=True)

    update = commands.add_parser("update")
    update.add_argument("--root", default=".")
    update.set_defaults(func=cmd_update)

    snapshot = commands.add_parser("snapshot")
    snapshot.add_argument("--root", default=".")
    snapshot.add_argument("--rev")
    snapshot.add_argument("-o", "--output", required=True)
    snapshot.set_defaults(func=cmd_snapshot)

    compare = commands.add_parser("diff")
    compare.add_argument("base")
    compare.add_argument("head")
    compare.add_argument("--view")
    compare.add_argument("--base-label")
    compare.add_argument("--head-label")
    compare.set_defaults(func=cmd_diff)

    view = commands.add_parser("view")
    view.add_argument("--root", default=".")
    view.add_argument("--base", default="HEAD")
    view.set_defaults(func=cmd_view)

    args = parser.parse_args()
    args.func(args)


if __name__ == "__main__":
    main()
