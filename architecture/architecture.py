#!/usr/bin/env python3
"""Derives a Rust workspace's code graph, checks it against the declared
components, and renders both into ARCHITECTURE.md.

The code graph holds every crate and module of the workspace. Crates and their
direct dependencies come from `cargo metadata`. Module dependencies come from
`cargo modules dependencies`, which reports module-level `use` declarations and
the types named in item signatures, each resolved to the path where the used
item is defined. Function bodies are not analyzed.

Components are the architecture as its authors see it. They are declared in
architecture.toml next to ARCHITECTURE.md. The architecture skill explains the
model and the check.

  architecture.py update [--root DIR]
      Regenerate the block between the markers in ARCHITECTURE.md, rewrite
      architecture.toml in canonical form, and print the check findings.
  architecture.py snapshot [--root DIR] [--rev REV] -o FILE
      Write the code graph and the components as JSON, of the working tree or
      of a revision, which is checked out into a temporary git worktree.
  architecture.py diff BASE HEAD [--view FILE]
      Print what changed between two snapshot files, and write the diff view.
      BASE may be "-" for an empty snapshot.
  architecture.py view [--root DIR] [--base REV]
      Write the diff view of the working tree against REV (default HEAD) to
      $TMPDIR and print its path.
"""
import argparse
import json
import os
import re
import shutil
import subprocess
import sys
import tempfile
import tomllib
from collections import defaultdict

DOC = "ARCHITECTURE.md"
TOML = "architecture.toml"
BEGIN = "<!-- architecture:begin (generated by architecture.py, do not edit) -->"
END = "<!-- architecture:end -->"

DEFAULT_HEADER = """\
# Components: the architecture as its authors see it.
# A component is realized by module or crate paths. A module belongs to the
# components of its most specific listed path, so a path covers its subtree down
# to the next listed path. The same path may be listed under several components.
# architecture.py rewrites this file in canonical form: components sorted by
# name, lists sorted, this header kept."""

GREEN = "stroke:#2da44e,stroke-width:3px"
RED = "stroke:#cf222e,stroke-width:3px,stroke-dasharray:6 4"
BLUE = "stroke:#0969da,stroke-width:3px"
UNEXPLAINED = "stroke:#cf222e,stroke-width:2px,stroke-dasharray:6 4"
TRANSITIVE = "stroke:#bf8700,stroke-width:2px,stroke-dasharray:6 4"
STALE = "stroke:#8c959f,stroke-dasharray:2 4"
GREY_NODE = "fill:#eaeef2,stroke:#8c959f,color:#57606a"
ADDED_NODE = "stroke:#2da44e,stroke-width:3px"
REMOVED_NODE = "stroke:#cf222e,stroke-width:3px,stroke-dasharray:6 4"

MERMAID_KEYWORDS = {"end", "graph", "subgraph", "flowchart", "style", "class",
                    "classDef", "linkStyle", "click", "direction", "default"}

DOT_EDGE = re.compile(r'^\s*"((?:[^"\\]|\\.)*)" -> "((?:[^"\\]|\\.)*)" \[label="(\w+)"')
DOT_NODE = re.compile(r'^\s*"((?:[^"\\]|\\.)*)" \[label="((?:[^"\\]|\\.)*)"')


def die(message):
    print(f"architecture.py: {message}", file=sys.stderr)
    sys.exit(1)


def run(cmd, cwd):
    result = subprocess.run(cmd, cwd=cwd, capture_output=True, text=True)
    if result.returncode != 0:
        die(f"{' '.join(cmd)} failed in {cwd}:\n{result.stderr.strip()}")
    return result.stdout


# ---------------------------------------------------------------------------
# Extraction: cargo metadata and cargo-modules into a snapshot.
#
# A snapshot is plain JSON, so the review can compare two revisions:
#   crates:        {crate: {target, deps, externals, dev, build}}
#   modules:       every module path of the workspace, crate roots included
#   uses:          [source module, target module, source item, target item]
#   external_uses: [module, external package]
#   components:    the canonical components of architecture.toml


def lib_name(package):
    """The crate name a package's library is referred to by in paths."""
    for target in package["targets"]:
        if set(target["kind"]) & {"lib", "rlib", "dylib", "cdylib", "staticlib", "proc-macro"}:
            return target["name"].replace("-", "_")
    return None


def analyzed_target(package):
    """The target cargo-modules analyzes: the library, else the first binary."""
    if lib_name(package):
        return "lib", ["--lib"], lib_name(package)
    bins = sorted(t["name"] for t in package["targets"] if "bin" in t["kind"])
    if bins:
        return "bin", ["--bin", bins[0]], bins[0].replace("-", "_")
    return None


def parse_dot(text):
    """Module paths with their kind, and the `uses` edges of a cargo-modules graph."""
    kinds, uses = {}, []
    for line in text.splitlines():
        if edge := DOT_EDGE.match(line):
            if edge.group(3) == "uses":
                uses.append((edge.group(1), edge.group(2)))
        elif node := DOT_NODE.match(line):
            header = node.group(2).split("|", 1)[0].split()
            kinds[node.group(1)] = header[-1] if header else ""
    return kinds, uses


def owner(path, modules):
    """The module that defines an item: the longest prefix of its path that is a module."""
    segments = path.split("::")
    for end in range(len(segments), 0, -1):
        prefix = "::".join(segments[:end])
        if prefix in modules:
            return prefix
    return None


def extract(root):
    if shutil.which("cargo-modules") is None:
        die("cargo-modules is not installed (cargo install cargo-modules)")
    meta = json.loads(run(["cargo", "metadata", "--format-version", "1"], root))
    packages = {p["id"]: p for p in meta["packages"]}
    resolve = {n["id"]: n for n in meta["resolve"]["nodes"]}

    packages_of_lib = defaultdict(list)
    for pid, package in packages.items():
        if name := lib_name(package):
            packages_of_lib[name].append(pid)

    closures = {}

    def closure(pid):
        if pid not in closures:
            seen, stack = set(), [pid]
            while stack:
                for dep in resolve.get(stack.pop(), {}).get("deps", []):
                    if dep["pkg"] not in seen:
                        seen.add(dep["pkg"])
                        stack.append(dep["pkg"])
            closures[pid] = seen
        return closures[pid]

    members = {}
    for pid in meta["workspace_members"]:
        target = analyzed_target(packages[pid])
        if target:
            members[pid] = target
    crate_of = {pid: crate for pid, (_, _, crate) in members.items()}

    crates, module_sets, raw_uses = {}, {}, {}
    for pid, (kind, flags, crate) in sorted(members.items(), key=lambda m: m[1][2]):
        deps = defaultdict(set)
        for dep in resolve[pid]["deps"]:
            for dep_kind in dep["dep_kinds"]:
                deps[dep_kind["kind"] or "normal"].add(dep["pkg"])
        crates[crate] = {
            "target": kind,
            "deps": sorted(crate_of[d] for d in deps["normal"] if d in crate_of),
            "externals": sorted(packages[d]["name"] for d in deps["normal"] if d not in crate_of),
            "dev": sorted(crate_of.get(d) or packages[d]["name"] for d in deps["dev"]),
            "build": sorted(crate_of.get(d) or packages[d]["name"] for d in deps["build"]),
            "_direct": sorted(deps["normal"]),
        }
        dot = run(["cargo", "modules", "dependencies", "--package", packages[pid]["name"],
                   *flags, "--no-sysroot", "--layout", "none"], root)
        kinds, uses = parse_dot(dot)
        module_sets[crate] = {p for p, k in kinds.items()
                              if k in ("crate", "mod") and (p == crate or p.startswith(crate + "::"))}
        raw_uses[crate] = uses

    uses, external_uses = set(), set()
    for crate, edges in raw_uses.items():
        direct = crates[crate].pop("_direct")
        for source, target in edges:
            source_module = owner(source, module_sets[crate])
            if source_module is None:
                continue
            target_crate = target.split("::", 1)[0]
            if target_crate in module_sets:
                target_module = owner(target, module_sets[target_crate]) or target_crate
                if target_module != source_module:
                    uses.add((source_module, target_module, source, target))
                continue
            # An item defined in a crate that is no direct dependency was reached
            # through a re-export, so it counts for the direct dependencies that
            # pull its crate in.
            candidates = packages_of_lib.get(target_crate, [])
            owners = [d for d in direct if d in candidates] or \
                     [d for d in direct if any(c in closure(d) for c in candidates)]
            for dep in owners:
                if dep in crate_of:
                    uses.add((source_module, crate_of[dep], source, target))
                else:
                    external_uses.add((source_module, packages[dep]["name"]))

    components, _ = load_components(root)
    return {
        "crates": crates,
        "modules": sorted(set().union(*module_sets.values())) if module_sets else [],
        "uses": sorted(list(u) for u in uses),
        "external_uses": sorted(list(u) for u in external_uses),
        "components": components,
    }


def empty_snapshot():
    return {"crates": {}, "modules": [], "uses": [], "external_uses": [], "components": []}


def snapshot_rev(rev, root):
    """The snapshot of a revision, extracted from a temporary git worktree."""
    top = run(["git", "rev-parse", "--show-toplevel"], root).strip()
    relative = os.path.relpath(os.path.abspath(root), top)
    scratch = tempfile.mkdtemp(prefix="architecture-")
    worktree = os.path.join(scratch, "worktree")
    try:
        run(["git", "worktree", "add", "--detach", "--quiet", worktree, rev], top)
        try:
            return extract(os.path.normpath(os.path.join(worktree, relative)))
        finally:
            run(["git", "worktree", "remove", "--force", worktree], top)
    finally:
        shutil.rmtree(scratch, ignore_errors=True)


